import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import '../avatar-client.js';
const A=globalThis.MapleAvatar;
const fixtures=JSON.parse(readFileSync(new URL('./avatar-vectors.json',import.meta.url)));
for(const f of fixtures)assert.equal(await A.encode(A.appearance(f.items)),f.code);
A.setCatalog(JSON.parse(readFileSync(new URL('../assets/coordi-catalog.json',import.meta.url))));
assert.equal(A.resolve(['안젤로 헤어']).items[0].id,65380);
const hat=A.suggestions('메르헨','모자',1)[0];
assert.deepEqual(A.selectName(['메르헨'],hat.name,0),[hat.name]);
const hats=A.suggestions('','모자');
const all=JSON.parse(readFileSync(new URL('../assets/coordi-catalog.json',import.meta.url))).items;
const ring=all.find(i=>i.part==='반지');
assert.throws(()=>A.selectName(Array(4).fill(ring.name),ring.name),/최대 4개/);
const overall=all.find(i=>i.part==='한벌옷'),top=all.find(i=>i.part==='상의'),bottom=all.find(i=>i.part==='하의');
assert.deepEqual(A.selectName([top.name,bottom.name],overall.name),[overall.name]);
assert.deepEqual(A.selectName([overall.name],top.name),[top.name]);
assert.match(await A.previewUrl([]),/^https:\/\/open\.api\.nexon\.com\/static\/maplestory\/character\/look\/[A-P]{1024}\?/);
assert.equal(await A.iconUrl({part:'피부',id:12018}),await A.iconUrl({part:'피부',id:12019}));
const merhen=A.suggestions('메르헨','',100);
assert.equal(merhen.length,new Set(merhen.map(i=>A.norm(i.name)+'|'+i.part)).size);
for(const i of merhen)assert.equal(A.identify(i.name)?.id,i.id,'icon and selected preview ID');
assert(A.relatedSets('피의 서약').length);
assert(A.relatedSets('스윗 메르헨').some(g=>g.rewards.some(i=>i.name==='스윗 메르헨')));
assert.equal(A.relatedSets('존재하지 않는 코디').length,0);
console.log('Avatar: 3 PC parity vectors, Angelo alias, query replacement, slot constraints, NEXON URL and skin icons passed');
